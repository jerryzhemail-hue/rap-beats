# 学位级别
LEVELS = {"2": "博士", "3": "硕士", "4": "学士"}

# 年份合法范围
MIN_YEAR = 1981   # 学位制度恢复（首批学士学位授予）
MAX_YEAR = datetime.now().year + 1  # 允许下一年度预案


def _school_name(code: str) -> str:
    return SCHOOL_CODES.get(code, "")


def validate(number: str, expect_school: str | None = None,
             expect_year: int | None = None) -> dict:
    """校验一个成人高等教育学士学位证书编号。"""
    errors: list[str] = []
    fields: dict = {}
    s = (number or "").strip().upper()

    if len(s) != 17:
        errors.append(f"总长度应为 17 位（C + 16 位数字），实际 {len(s)} 位")
    if not s.startswith("C"):
        errors.append("首位应为字母 C（成人高等教育标识）")

    body = s[1:] if len(s) >= 1 else ""

    is_self_exam = False
    if len(body) == 16 and body[10] == "Z":
        is_self_exam = True

    if len(body) == 16:
        check = list(body)
        if is_self_exam:
            check[10] = "0"
        if not all(ch.isdigit() for ch in check):
            errors.append("除前缀 C 及自考 Z 标记外，其余位必须为数字")
    else:
        if body and not body.isdigit():
            errors.append("除前缀 C 外，其余位必须为数字")

    if len(body) != 16:
        return {"valid": False, "errors": errors, "fields": fields}

    school = body[0:5]
    level = body[5]
    year_s = body[6:10]
    serial = body[10:16]

    if not school.isdigit():
        errors.append(f"学校代码应为 5 位数字：{school!r}")
    fields["school_code"] = school
    fields["school_name"] = _school_name(school)
    if expect_school and school != expect_school:
        errors.append(f"学校代码应为 {expect_school}，实际 {school}")

    if level.isdigit():
        fields["level"] = LEVELS.get(level, f"未知级别({level})")
        if level != "4":
            errors.append(f"学士学位级别码应为 4，实际为 {level}")
    else:
        fields["level"] = "非数字"
        errors.append(f"学位级别码应为数字 4，实际为 {level!r}")

    fields["year"] = year_s
    if not year_s.isdigit():
        errors.append(f"授予年份应为 4 位数字：{year_s!r}")
    else:
        y = int(year_s)
        if not (MIN_YEAR <= y <= MAX_YEAR):
            errors.append(f"授予年份 {y} 不在合理范围 {MIN_YEAR}-{MAX_YEAR}")
        if expect_year and y != expect_year:
            errors.append(f"授予年份应为 {expect_year}，实际 {y}")

    if is_self_exam:
        fields["serial"] = "Z" + serial[1:]
        if not serial[1:].isdigit():
            errors.append(f"自考序号应为 Z + 5 位数字：{fields['serial']!r}")
    else:
        fields["serial"] = serial
        if not serial.isdigit():
            errors.append(f"流水号应为 6 位数字：{serial!r}")

    fields["type"] = "自考" if is_self_exam else "成人高等教育"
    fields["valid"] = len(errors) == 0
    return {"valid": len(errors) == 0, "errors": errors, "fields": fields}


def make_template(school_code: str, year: int, self_exam: bool = False) -> str:
    """按格式生成一个“模板占位”示例（仅用于演示格式，非真实编号）。"""
    school_code = school_code.zfill(5)
    level = "4"
    serial = ("Z00001" if self_exam else "000001")
    return f"C{school_code}{level}{year}{serial}"


if __name__ == "__main__":
    import sys

    examples = [
        "C1047642023009856",
        "C1000842023000001",
        "C1000842023",
        "C100084X2023000001",
        "D1047642023009856",
    ]
    for n in examples:
        r = validate(n)
        print(f"编号: {n}")
        print(f"  有效: {r['valid']}")
        if r["errors"]:
            print(f"  错误: {r['errors']}")
        else:
            f = r["fields"]
            print(f"  类型: {f.get('type')} | 学校: {f.get('school_code')}"
                  f"({f.get('school_name') or '未知'}) | 级别: {f.get('level')}"
                  f" | 年份: {f.get('year')} | 序号: {f.get('serial')}")
        print()

    if len(sys.argv) > 1:
        print("命令行校验结果：")
        for n in sys.argv[1:]:
            r = validate(n)
            print(f"  {n} -> {'有效' if r['valid'] else '无效'} "
                  f"{'' if r['valid'] else r['errors']}")
